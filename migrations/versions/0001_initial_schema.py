"""Initial TransitPulse schema.

Hand-written rather than autogenerated: declarative partitioning, partial
indexes and the partition-maintenance function all live outside what Alembic
can reflect, and a half-autogenerated migration that silently drops the
PARTITION BY clause is worse than no autogeneration at all.

Design notes worth keeping:

* ``vehicle_events`` is RANGE-partitioned on ``event_time`` by day. Postgres
  prunes partitions for the "last N hours" queries the API serves, and dropping
  a day of history becomes a ``DETACH``/``DROP`` instead of a ``DELETE`` that
  bloats the table. The partition key has to be part of every unique
  constraint, which is why the primary key is ``(idempotency_key, event_time)``
  rather than the key alone.
* ``vehicle_live`` is a separate narrow table, one row per vehicle. Serving the
  live map from the partitioned history would mean a scan per request; here it
  is a single index lookup.

Revision ID: 0001
Revises: None
"""

